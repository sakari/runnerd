// Adds a `TestStore` Xcode build configuration so the RevenueCat Test Store
// can be exercised in a standalone on-device build.
//
// The two requirements pull in opposite directions:
//
//   * The app must run untethered, so it has to load the embedded JS bundle.
//     Expo's AppDelegate picks the bundle URL with `#if DEBUG` — a debug build
//     always goes to Metro — so the *app* target must not have DEBUG.
//   * RevenueCat's SDK alerts and crashes on a `test_` key outside a debug
//     build, so the *RevenueCat pod* must have DEBUG.
//
// Hence: clone the Release configuration (app target stays non-debug, bundle
// gets embedded), then map that configuration to CocoaPods' debug mode so
// every pod — RevenueCat included — compiles with DEBUG.
//
// `ios/` is gitignored and regenerated by prebuild, which is why this is a
// plugin rather than a one-off edit.

const fs = require("node:fs");
const path = require("node:path");
const { withXcodeProject, withDangerousMod } = require("@expo/config-plugins");

const CONFIGURATION = "TestStore";

function withClonedReleaseConfiguration(config) {
  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const buildConfigs = project.pbxXCBuildConfigurationSection();
    const lists = project.pbxXCConfigurationList();
    let cloned = 0;

    for (const key of Object.keys(lists)) {
      if (key.endsWith("_comment")) continue;
      const refs = lists[key].buildConfigurations;
      if (!Array.isArray(refs)) continue;
      // Idempotent: prebuild may run against an already-patched project.
      if (refs.some((ref) => ref.comment === CONFIGURATION)) continue;

      const releaseRef = refs.find((ref) => ref.comment === "Release");
      if (!releaseRef) continue;
      const release = buildConfigs[releaseRef.value];
      if (!release) continue;

      const clone = JSON.parse(JSON.stringify(release));
      clone.name = CONFIGURATION;
      clone.buildSettings = {
        ...clone.buildSettings,
        // Xcode exports build settings into script-phase environments, and
        // `expo export:embed` runs in one — so this reaches the bundler and is
        // inlined as process.env.EXPO_PUBLIC_USE_TEST_STORE. It is how the JS
        // knows it may use the Test Store key, since __DEV__ is false here.
        EXPO_PUBLIC_USE_TEST_STORE: "1",
      };

      const uuid = project.generateUuid();
      buildConfigs[uuid] = clone;
      buildConfigs[`${uuid}_comment`] = CONFIGURATION;
      refs.push({ value: uuid, comment: CONFIGURATION });
      cloned += 1;
    }

    if (cloned === 0 && !hasConfiguration(buildConfigs)) {
      throw new Error(
        `with-test-store-configuration: found no Release build configuration to clone. ` +
          `The Xcode project layout has changed and this plugin needs updating.`,
      );
    }
    return cfg;
  });
}

function hasConfiguration(buildConfigs) {
  return Object.keys(buildConfigs).some(
    (key) => !key.endsWith("_comment") && buildConfigs[key]?.name === CONFIGURATION,
  );
}

function withPodfileDebugMapping(config) {
  return withDangerousMod(config, [
    "ios",
    (cfg) => {
      const podfile = path.join(cfg.modRequest.platformProjectRoot, "Podfile");
      const contents = fs.readFileSync(podfile, "utf8");
      if (contents.includes(`'${CONFIGURATION}' => :debug`)) return cfg;

      const target = /^(target ['"][^'"]+['"] do)$/m;
      if (!target.test(contents)) {
        throw new Error(
          "with-test-store-configuration: could not find the target block in ios/Podfile. " +
            "Without the CocoaPods debug mapping, RevenueCat would reject the Test Store key.",
        );
      }

      const mapping =
        `\n  # ${CONFIGURATION} is a clone of Release, so pods would otherwise build\n` +
        `  # without DEBUG and RevenueCat would refuse the Test Store key.\n` +
        `  project '${cfg.modRequest.projectName}', '${CONFIGURATION}' => :debug\n`;

      fs.writeFileSync(podfile, contents.replace(target, (match) => match + mapping));
      return cfg;
    },
  ]);
}

module.exports = function withTestStoreConfiguration(config) {
  return withPodfileDebugMapping(withClonedReleaseConfiguration(config));
};
